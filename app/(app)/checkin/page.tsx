import Link from "next/link";
import { requireAuth } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { Alert, Card } from "@/components/ui";
import { SelfCheckIn } from "@/components/self-checkin";
import { formatDate } from "@/lib/utils";

export const metadata = { title: "Check in" };
export const dynamic = "force-dynamic";

export default async function CheckinPage({
  searchParams,
}: {
  searchParams: Promise<{ o?: string; s?: string; k?: string }>;
}) {
  const ctx = await requireAuth();
  const { o, s, k } = await searchParams;

  if (!s || !k) {
    return (
      <div className="mx-auto max-w-md">
        <Card>
          <h1 className="font-display text-xl font-semibold">Check-in</h1>
          <p className="mt-2 text-sm text-ink-500">
            Scan the QR code shown at the entrance, or ask your welcome team for the check-in link.
          </p>
          <Link href="/dashboard" className="mt-4 inline-block text-xs font-semibold text-royal-700 hover:underline">
            Back to dashboard
          </Link>
        </Card>
      </div>
    );
  }

  const orgId = o ?? ctx.activeOrg?.id ?? "";
  const supabase = await createClient();
  const { data, error } = orgId
    ? await supabase.rpc("qr_session_status", { target_org: orgId, p_session: s, secret: k })
    : { data: null, error: { message: "This check-in link is incomplete." } };

  if (error || !data) {
    return (
      <div className="mx-auto max-w-md">
        <Card>
          <h1 className="font-display text-xl font-semibold">Check-in unavailable</h1>
          <div className="mt-3">
            <Alert tone="danger">{error?.message ?? "This check-in code is not valid."}</Alert>
          </div>
          <p className="mt-3 text-xs text-ink-500">
            Codes expire and can be regenerated by an administrator. Ask your welcome team for a fresh link.
          </p>
        </Card>
      </div>
    );
  }

  const info = data as { session_id: string; title: string; session_date: string; expires_at: string };

  return (
    <div className="mx-auto max-w-md">
      <Card>
        <p className="text-xs font-semibold uppercase tracking-[0.2em] text-royal-700">Check-in</p>
        <h1 className="mt-1 font-display text-2xl font-semibold">{info.title}</h1>
        <p className="mt-1 text-sm text-ink-500">{formatDate(info.session_date, ctx.activeOrg?.timezone)}</p>
        <div className="mt-5">
          <SelfCheckIn orgId={orgId} sessionId={info.session_id} secret={k} />
        </div>
      </Card>
    </div>
  );
}
